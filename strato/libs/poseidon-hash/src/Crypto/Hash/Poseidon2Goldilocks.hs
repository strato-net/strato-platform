   in zipWith (\x d -> addF total (mulF x d)) s matrixDiag

addRC :: Int -> [Word64] -> [Word64]
addRC r = zipWith addF (externalConstants !! r)

-- | The Poseidon2 permutation on 12 canonical elements.
permutation :: [Word64] -> [Word64]
permutation input
  | length input /= 12 = error "Poseidon2Goldilocks: permutation needs 12 elements"
  | otherwise =
      let s0 = externalLayer input
          full s r = externalLayer (map sbox (addRC r s))
          s1 = foldl' full s0 [0 .. 3]
          partial s r = case s of
            (h : t) -> internalLayer (sbox (addF h (internalConstants !! r)) : t)
            [] -> error "Poseidon2Goldilocks: empty state"
          s2 = foldl' partial s1 [0 .. 21]
          s3 = foldl' full s2 [4 .. 7]
       in s3

-- | plonky2 @hash_n_to_m_no_pad@: absorb 8 elements per permutation by
-- overwriting the first lanes, then squeeze @m@ elements (8 per
-- permutation). Inputs must be canonical.
hashNToM :: Int -> [Word64] -> [Word64]
hashNToM m inputs
  | any (not . isCanonical) inputs = error "Poseidon2Goldilocks: non-canonical input"
  | otherwise = squeeze m (absorbAll (replicate 12 0) inputs)
  where
    absorbAll st [] = st
    absorbAll st xs =
      let (blk, rest) = splitAt 8 xs
          st' = permutation (blk ++ drop (length blk) st)
       in absorbAll st' rest
    squeeze n st
      | n <= 8 = take n st
      | otherwise = take 8 st ++ squeeze (n - 8) (permutation st)

-- | Pack bytes into canonical elements: 7-byte little-endian chunks (the
-- last one zero-padded), followed by ONE element holding the byte length so
-- payloads differing only in trailing zeros commit differently.
packBytes :: B.ByteString -> [Word64]
packBytes bs = go bs ++ [fromIntegral (B.length bs)]
  where
    go b
      | B.null b = []
      | otherwise =
          let (c, rest) = B.splitAt 7 b
           in le c : go rest
    le c = foldr (\w acc -> (acc `shiftL` 8) .|. fromIntegral w) 0 (B.unpack c)

-- | hashNToM over 'packBytes'.
hashBytes :: Int -> B.ByteString -> [Word64]
hashBytes m = hashNToM m . packBytes

