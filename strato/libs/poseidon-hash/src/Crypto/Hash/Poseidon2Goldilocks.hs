-- |
-- Module      : Crypto.Hash.Poseidon2Goldilocks
-- Description : Poseidon2 over the Goldilocks field (plonky2 / Plonky3 parameters)
--
-- Poseidon2 over GF(p), p = 2^64 - 2^32 + 1 (Goldilocks), WIDTH 12, RATE 8,
-- S-box x^7, 8 full + 22 partial rounds — the algebraic hasher of the
-- plonky2 (elliottech fork) / Plonky3 Goldilocks ecosystem: Polygon's
-- Plonky2/3-based provers, zkSync's Boojum, Lighter, and STRATO's own
-- rollup use this exact instance for state trees, DA commitments and
-- signature messages. It is bit-for-bit @plonky2::hash::poseidon2@ with the
-- fork's constants ('Crypto.Hash.Poseidon2Goldilocks.Constants'); the test
-- suite pins vectors generated by that prover.
--
-- Provided: the permutation, plonky2's @hash_n_to_m_no_pad@ sponge (absorb
-- 8 elements per permutation by OVERWRITING the rate lanes, no padding, so
-- callers hash fixed-shape inputs exactly as circuits do), and a
-- byte-string convenience that packs 7-byte little-endian chunks (always
-- canonical) followed by the byte length.
module Crypto.Hash.Poseidon2Goldilocks
  ( goldilocksPrime
  , isCanonical
  , permutation
  , hashNToM
  , hashBytes
  , packBytes
  ) where

import Crypto.Hash.Poseidon2Goldilocks.Constants
import Data.Bits (shiftL, (.|.))
import qualified Data.ByteString as B
import Data.List (foldl')
import Data.Word (Word64)

-- | p = 2^64 - 2^32 + 1
goldilocksPrime :: Word64
goldilocksPrime = 0xFFFFFFFF00000001

isCanonical :: Word64 -> Bool
isCanonical x = x < goldilocksPrime

-- ---------------------------------------------------------------- field

-- Elements are canonical Word64s. Products go through Integer for the
-- 128-bit intermediate; everything else stays in Word64.

addF :: Word64 -> Word64 -> Word64
addF a b =
  let !s = a + b            -- wraps mod 2^64
      !carried = s < a      -- overflow past 2^64 == subtract p and add 2^32-1... see below
   in if carried
        then canon (s + 0xFFFFFFFF)     -- 2^64 ≡ 2^32 - 1 (mod p)
        else canon s

canon :: Word64 -> Word64
canon x = if x >= goldilocksPrime then x - goldilocksPrime else x

mulF :: Word64 -> Word64 -> Word64
mulF a b = fromInteger ((toInteger a * toInteger b) `rem` toInteger goldilocksPrime)

-- x^7
sbox :: Word64 -> Word64
sbox x =
  let !x2 = mulF x x
      !x4 = mulF x2 x2
      !x6 = mulF x4 x2
   in mulF x6 x

-- ---------------------------------------------------------- linear layers

-- circulant M4 on a 4-lane block: (2 3 1 1 / 1 2 3 1 / 1 1 2 3 / 3 1 1 2)
mat4 :: [Word64] -> [Word64]
mat4 [x0, x1, x2, x3] =
  let t01 = addF x0 x1
      t23 = addF x2 x3
      t0123 = addF t01 t23
      t01123 = addF t0123 x1
      t01233 = addF t0123 x3
      y3 = addF t01233 (addF x0 x0)
      y1 = addF t01123 (addF x2 x2)
      y0 = addF t01123 t01
      y2 = addF t01233 t23
   in [y0, y1, y2, y3]
mat4 _ = error "Poseidon2Goldilocks: mat4 needs 4 lanes"

externalLayer :: [Word64] -> [Word64]
externalLayer s =
  let blocks = map mat4 (chunks4 s)
      s' = concat blocks
      sums = [ foldl' addF 0 [ s' !! (4 * j + k) | j <- [0 .. 2] ] | k <- [0 .. 3] ]
   in [ addF (s' !! i) (sums !! (i `mod` 4)) | i <- [0 .. 11] ]
  where
    chunks4 [] = []
    chunks4 xs = take 4 xs : chunks4 (drop 4 xs)

